const fs = require('node:fs/promises');
const path = require('node:path');
const {randomUUID} = require('node:crypto');

const shellQuote = value => "'" + value.replaceAll("'", "'\\''") + "'";
const batchQuote = value => '"' + value.replaceAll('%', '%%') + '"';
async function atomic(file, text, mode=0o600) {
  const tmp=file+'.'+randomUUID()+'.tmp';
  try {await fs.writeFile(tmp,text,{mode,flag:'wx'});await fs.rename(tmp,file);await fs.chmod(file,mode);} finally {await fs.rm(tmp,{force:true});}
}
async function prepareRuntime(workspace, {executable, appRoot, coreRoot, noSymlinks}) {
  workspace=await fs.realpath(workspace);
  const local=path.join(workspace,'.local');await noSymlinks(local);await fs.mkdir(local,{recursive:true});
  const runner=path.join(appRoot,'runner.cjs');
  const command=path.join(local,'career'),windowsCommand=command+'.cmd';
  for(const name of [command,windowsCommand,path.join(local,'desktop-runtime.json')])await noSymlinks(name);
  // Use this script's directory at execution time, so moving a workspace never points at its old copy.
  await atomic(command,`#!/bin/sh\n# Generated by career desktop. Local machine only.\nCAREER_WORKSPACE_DIR="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)" || exit 1\nexport ELECTRON_RUN_AS_NODE=1\nexec ${shellQuote(executable)} ${shellQuote(runner)} --workspace "$CAREER_WORKSPACE_DIR" "$@"\n`,0o755);
  await atomic(windowsCommand,`@echo off\r\nrem Generated by career desktop. Local machine only.\r\nsetlocal DisableDelayedExpansion\r\nchcp 65001 >nul\r\nset "ELECTRON_RUN_AS_NODE=1"\r\n${batchQuote(executable)} ${batchQuote(runner)} --workspace "%~dp0.." %*\r\nexit /b %errorlevel%\r\n`);
  await atomic(path.join(local,'desktop-runtime.json'),JSON.stringify({schema:'career-desktop-runtime/v1',executable,runner,coreRoot,workspace},null,2)+'\n');
  return {workspace,command,windowsCommand};
}
function handoffPrompt(workspace, platform=process.platform) {
  const command=platform==='win32'?'& .\\.local\\career.cmd':'./.local/career';
  return `请接手这个 career 工作区：\n${workspace}\n\n先读取 AGENTS.md。在这个目录运行 ${command} doctor --json 和 ${command} workspace status --json，按检查结果继续初始化或已有进度。首次使用请引导我整理经历、研究适合的岗位要求，再生成第一份可编辑简历。一步一步来，边聊边保存，不编造经历；如果我已指定任务，以我的任务为准。CLI 和 Skills 已随桌面软件准备好，无需另装 Node/npm。`;
}
function boundArguments(argv) {
  if(argv[0]!=='--workspace'||!argv[1]||!path.isAbsolute(argv[1]))throw new Error('请使用工作区内的 .local/career 入口。');
  const args=argv.slice(2);
  if(args.some(a=>a==='--workspace'||a.startsWith('--workspace=')))throw new Error('此入口已绑定工作区；请使用目标目录里的 CLI 入口。');
  if(args[0]==='setup'||(args[0]==='workspace'&&['setup','restore'].includes(args[1])))throw new Error('请在 career 软件中创建或打开工作区；当前入口不创建其他目录。');
  return {workspace:path.resolve(argv[1]),args};
}
module.exports={prepareRuntime,handoffPrompt,boundArguments};
